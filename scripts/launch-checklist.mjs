#!/usr/bin/env node

/**
 * The phase 4 launch checklist, generated from the route manifest.
 *
 * A hand-written checklist is a snapshot of what somebody believed the release did
 * on the day they wrote it. This one is derived from the same file that generates
 * the redirects, so it cannot describe a release that is not the release.
 *
 * Run: npm run launch:checklist
 *
 * @see tasks/repositioning/IMPLEMENTATION-SPEC.md section 3
 */
import { existsSync } from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const manifest = require(path.join(process.cwd(), 'src/lib/route-manifest.js'));

const { ROUTES, PHASE_4_REDIRECTS, ACTIVE_PHASES, getRedirectsForPhases, getSitemapRoutes } =
  manifest;

const SHIPPED_PHASES = ['active', 'phase4'];
const before = getRedirectsForPhases(ACTIVE_PHASES).filter((r) => r.permanent);
const after = getRedirectsForPhases(SHIPPED_PHASES).filter((r) => r.permanent);
const beforeBySource = new Map(before.map((r) => [r.source, r.destination]));

const newRedirects = after.filter((r) => !beforeBySource.has(r.source));
const changedRedirects = after.filter(
  (r) => beforeBySource.has(r.source) && beforeBySource.get(r.source) !== r.destination
);

/** A route file that still exists for a path that will redirect. */
function pageFileFor(routePath) {
  if (routePath.includes(':')) return null;
  const segments = routePath === '/' ? [] : routePath.slice(1).split('/');
  const candidate = path.join(process.cwd(), 'src/app', ...segments, 'page.tsx');
  return existsSync(candidate) ? path.relative(process.cwd(), candidate) : null;
}

const deadPages = PHASE_4_REDIRECTS.map((route) => pageFileFor(route.path)).filter(Boolean);

const dynamicChildren = PHASE_4_REDIRECTS.filter((route) => route.path.includes(':')).map(
  (route) => route.path
);

const lines = [];
const push = (line = '') => lines.push(line);

push('# Phase 4 launch checklist');
push();
push('Generated by `npm run launch:checklist` from `src/lib/route-manifest.js`.');
push('Do not edit by hand: a hand-written checklist describes the release somebody');
push('remembered, not the one the code performs.');
push();
push(`Active phases today: ${ACTIVE_PHASES.join(', ')}`);
push(`Active phases after release: ${SHIPPED_PHASES.join(', ')}`);
push();

push('## What the release commit contains');
push();
push('1. `ACTIVE_PHASES` in `src/lib/route-manifest.js` gains `phase4`. One line.');
push(`2. ${deadPages.length} page file(s) deleted, listed below. They become unreachable the`);
push('   moment the redirect is emitted, because a Next redirect takes precedence');
push('   over a page at the same path. Deleting them in the same commit is what');
push('   stops the old position sitting in the repository as live-looking code.');
push('3. Nothing else. Every page, component and copy change is already merged.');
push();

push(`## Redirects that go live (${newRedirects.length})`);
push();
for (const redirect of newRedirects.sort((a, b) => a.source.localeCompare(b.source))) {
  push(`- [ ] \`${redirect.source}\` → \`${redirect.destination}\``);
}
push();

if (changedRedirects.length > 0) {
  push(`## Redirects that change destination (${changedRedirects.length})`);
  push();
  push('These already redirect. The release repoints them, because their current');
  push('destination is itself retiring and leaving them would form a chain.');
  push();
  for (const redirect of changedRedirects) {
    push(
      `- [ ] \`${redirect.source}\`: was \`${beforeBySource.get(redirect.source)}\`, becomes \`${redirect.destination}\``
    );
  }
  push();
}

push(`## Page files to delete (${deadPages.length})`);
push();
for (const file of deadPages.sort()) {
  push(`- [ ] \`${file}\``);
}
if (dynamicChildren.length > 0) {
  push();
  push('Plus every child of these patterns, whose parent directory goes with them:');
  for (const pattern of dynamicChildren) push(`- [ ] \`${pattern}\``);
}
push();

push('## Verify after deploy');
push();
push('Check each redirected URL returns 308 and lands on a 200, not on another');
push('redirect. The manifest test proves this against the declaration; this proves');
push('it against production.');
push();
push('```bash');
push('for u in \\');
for (const redirect of after.slice(0, 40)) {
  if (redirect.source.includes(':')) continue;
  push(`  ${redirect.source} \\`);
}
push('  ; do curl -sIL -o /dev/null -w "%{http_code} %{url_effective}\\n" \\');
push('    "https://www.orangejelly.co.uk$u"; done');
push('```');
push();
push(`Then confirm the sitemap lists ${getSitemapRoutes().length} static routes and none of the`);
push('redirected paths above:');
push();
push('```bash');
push('curl -s https://www.orangejelly.co.uk/sitemap.xml | grep -c "<url>"');
push('```');
push();

push('## Rollback');
push();
push('**Trigger:** any redirected URL returning a 404 or a chain, the enquiry form');
push('failing to write a contact row, or an uncaught error on `/`, `/start-here`');
push('or `/results`.');
push();
push('**Action:** revert the release commit and redeploy. It is one commit, and it');
push('contains only the phase flip and the deletions, so the revert restores both');
push('the old pages and the old redirect table in a single step. Nothing in the');
push('release writes to the database, so there is no data to unwind.');
push();
push('**Not a trigger:** a ranking movement. Consolidation moves rankings around for');
push('weeks and reverting on day two would cost more authority than it saved.');
push();
push('**Owner:** Peter Pitcher. Single responder, single mailbox');
push('(`peter@orangejelly.co.uk`). Reachable for 48 hours after the release.');
push();
push('**Window:** deploy on a weekday morning, never on a Friday and never before a');
push('day nobody is available.');
push();

push('## Before you press it');
push();
push('- [ ] `npm run lint` clean');
push('- [ ] `npm run type-check` clean');
push('- [ ] `npm test` green, including the simulated phase 4 redirect table');
push('- [ ] `npm run build` clean, including the positioning gate');
push('- [ ] The positioning gate reports no remaining phase 4 exemptions');
push('- [ ] Enquiry form submitted end to end against production Supabase and Resend');
push('- [ ] Search Console open, so the crawl can be watched rather than assumed');
push();

const total =
  newRedirects.length + changedRedirects.length + deadPages.length + dynamicChildren.length;
push(`_${total} checkable items. Generated from ${ROUTES.length} declared routes._`);

console.log(lines.join('\n'));
